/**
 * Normalizes input text for fuzzy searching (lowercase, removing accents and punctuation).
 */
export function normalizeSearchString(val: string): string {
  return (val || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Search the provider directory across name, aliases, categories, and description.
 */
export function searchProviders(
  query: string,
  categoryFilter?: DirectoryCategoryId | 'all'
): BankProvider[] {
  let list = PROVIDER_DIRECTORY;

  if (categoryFilter && categoryFilter !== 'all') {
    list = list.filter((p) => p.categoryIds.includes(categoryFilter));
  }

  const cleanQuery = normalizeSearchString(query);
  if (!cleanQuery) {
    return list;
  }

  const terms = cleanQuery.split(' ').filter(Boolean);

  return list.filter((provider) => {
    const haystack = normalizeSearchString(
      `${provider.name} ${provider.shortName} ${provider.aliases.join(' ')} ${provider.categoryIds.join(' ')} ${provider.id} ${provider.description || ''}`
    );

    // Every search term should match somewhere in the provider's haystack
    return terms.every((term) => haystack.includes(term));
  });
}

/**
 * Look up a provider by its ID or alias/name.
 */
export function findProvider(idOrName: string): BankProvider | undefined {
  if (!idOrName) return undefined;
  const lower = idOrName.toLowerCase().trim();

  // 1. Direct ID match
  const exactId = PROVIDER_DIRECTORY.find((p) => p.id.toLowerCase() === lower);
  if (exactId) return exactId;

  // 2. Direct name match
  const exactName = PROVIDER_DIRECTORY.find(
    (p) => p.name.toLowerCase() === lower || p.shortName.toLowerCase() === lower
  );
  if (exactName) return exactName;

  // 3. Alias check
  const aliasMatch = PROVIDER_DIRECTORY.find((p) =>
    p.aliases.some((a) => a.toLowerCase() === lower)
  );
  if (aliasMatch) return aliasMatch;

  // 4. Fuzzy fallback match (e.g., "bpi express" contains "bpi", "gcash personal" contains "gcash")
  const norm = normalizeSearchString(idOrName);
  return PROVIDER_DIRECTORY.find((p) => {
    const pNorm = normalizeSearchString(p.name);
    return norm.includes(pNorm) || pNorm.includes(norm);
  });
}

/**
 * Get popular/trending providers for quick selection.
 */
export function getPopularProviders(): BankProvider[] {
  return PROVIDER_DIRECTORY.filter((p) => p.popular);
}
