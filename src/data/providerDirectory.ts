/**
 * Lookup provider by exact id or fuzzy name matching
 */
export function findProvider(idOrName: string): BankProvider | undefined {
  if (!idOrName) return undefined;
  const clean = idOrName.toLowerCase().trim();

  // Exact ID match
  const byId = PROVIDER_DIRECTORY.find((p) => p.id.toLowerCase() === clean);
  if (byId) return byId;

  // Normalized shortName match
  const byShort = PROVIDER_DIRECTORY.find(
    (p) => p.shortName.toLowerCase() === clean
  );
  if (byShort) return byShort;

  // Name match
  const byName = PROVIDER_DIRECTORY.find(
    (p) => p.name.toLowerCase() === clean || clean.includes(p.name.toLowerCase())
  );
  if (byName) return byName;

  // Keyword match
  const byKeyword = PROVIDER_DIRECTORY.find((p) =>
    p.keywords?.some((k) => k.toLowerCase() === clean || clean.includes(k.toLowerCase()))
  );
  if (byKeyword) return byKeyword;

  return undefined;
}

/**
 * Popular / Top institutions in the Philippines
 */
export function getPopularProviders(): BankProvider[] {
  return PROVIDER_DIRECTORY.filter((p) => p.isPopular);
}

/**
 * Filter and search the provider directory
 */
export function searchProviders(
  query: string,
  categoryId?: DirectoryCategoryId | 'all'
): BankProvider[] {
  const cleanQuery = (query || '').toLowerCase().trim();

  return PROVIDER_DIRECTORY.filter((prov) => {
    // Category check
    if (categoryId && categoryId !== 'all') {
      if (!prov.categoryIds.includes(categoryId)) {
        return false;
      }
    }

    // Query check
    if (!cleanQuery) return true;

    if (prov.id.toLowerCase().includes(cleanQuery)) return true;
    if (prov.name.toLowerCase().includes(cleanQuery)) return true;
    if (prov.shortName.toLowerCase().includes(cleanQuery)) return true;
    if (prov.keywords?.some((k) => k.toLowerCase().includes(cleanQuery))) {
      return true;
    }

    return false;
  });
}
